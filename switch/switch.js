let a = prompt("Enter the Number to Display the Day :")

switch (a) {
    case 1:
            console.log("Monday");
        break;

    case 2:
            console.log("Tuesday");
        break;


    case 3:
            console.log("Wednesday");
        break;

    default:
        console.log("Invalid Choice !!!");
        break;
}